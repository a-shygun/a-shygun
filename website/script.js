const root = document.documentElement;
const themeToggle = document.querySelector("#theme-toggle");
const languageToggle = document.querySelector("#language-toggle");
const languageName = document.querySelector("#language-name");
const themeColor = document.querySelector('meta[name="theme-color"]');
const repositoryMetricValues = new Map();
let language = getPreference("portfolio-language", "en", ["en", "fa"]);
let theme = getPreference("portfolio-theme", "dark", ["dark", "light"]);

function getPreference(key, fallback, allowedValues) {
  try {
    const value = localStorage.getItem(key);
    return allowedValues.includes(value) ? value : fallback;
  } catch {
    return fallback;
  }
}

function savePreference(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // Preferences still apply for this page view when storage is unavailable.
  }
}

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  const rtl = language === "fa";
  root.lang = language;
  root.dir = rtl ? "rtl" : "ltr";
  document.title = rtl ? "امیر شایگان — توسعه‌دهنده و مهندس داده" : "Amir Shygun — Developer & Data Engineer";
  document.querySelector('meta[name="description"]').content = rtl
    ? "امیر شایگان — توسعه‌دهندهٔ فرانت‌اند و مهندس داده در رشت. پروژه‌های متن‌باز، مهارت‌ها و تجربه‌ها."
    : "Amir Shygun — frontend developer and data engineer in Rasht, Iran. Selected open-source projects, skills, and experience.";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = translations[language][element.dataset.i18nAlt];
    if (value !== undefined) element.alt = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = translations[language][element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-cert-en]").forEach((image) => {
    const asset = image.dataset[rtl ? "certFa" : "certEn"];
    if (image instanceof HTMLImageElement) image.src = asset;
    if (image instanceof HTMLAnchorElement) image.href = asset;
  });
  syncThemeToggle();
  languageToggle.setAttribute("aria-label", translations[language].switchLanguage);
  languageName.textContent = translations[language].languageName;
  renderRepositoryMetrics();
  savePreference("portfolio-language", language);
}

function syncThemeToggle() {
  const isDark = theme === "dark";
  themeToggle.querySelector(".visually-hidden").textContent = translations[language][isDark ? "themeLight" : "themeDark"];
  themeToggle.querySelector(".theme-icon").innerHTML = isDark
    ? '<svg viewBox="0 0 24 24"><circle cx="12" cy="12" r="3.5"></circle><path d="M12 2v2m0 16v2M4.93 4.93l1.42 1.42m11.3 11.3 1.42 1.42M2 12h2m16 0h2M4.93 19.07l1.42-1.42m11.3-11.3 1.42-1.42"></path></svg>'
    : '<svg viewBox="0 0 24 24"><path d="M20.5 15.2A8.5 8.5 0 0 1 8.8 3.5 8.5 8.5 0 1 0 20.5 15.2Z"></path></svg>';
  themeToggle.setAttribute("aria-label", translations[language][isDark ? "switchToLight" : "switchToDark"]);
}

function applyTheme(nextTheme) {
  theme = nextTheme;
  root.dataset.theme = theme;
  const isDark = theme === "dark";
  syncThemeToggle();
  const graph = document.querySelector("#contribution-graph");
  graph.src = `https://ghchart.xqsit94.in/${isDark ? "dark:5688FF" : "light:3975F6"}/a-shygun`;
  themeColor.content = isDark ? "#111214" : "#f1f0ec";
  savePreference("portfolio-theme", theme);
}

function renderRepositoryMetrics() {
  const numberFormat = new Intl.NumberFormat(language === "fa" ? "fa-IR" : "en-US");
  repositoryMetricValues.forEach((values, repository) => {
    Object.entries(values).forEach(([metric, value]) => {
      const element = document.querySelector(`[data-repo="${repository}"][data-metric="${metric}"]`);
      if (element) element.textContent = numberFormat.format(value);
    });
  });
}

async function loadRepositoryMetrics() {
  const repositories = ["dripfetch", "Terrascope", "Playlistr"];
  await Promise.allSettled(repositories.map(async (repository) => {
    const base = `https://api.github.com/repos/a-shygun/${repository}`;
    const [repoResponse, issuesResponse, pullsResponse] = await Promise.all([
      fetch(base, { headers: { Accept: "application/vnd.github+json" } }),
      fetch(`https://api.github.com/search/issues?q=repo:a-shygun/${repository}+is:issue+is:open`, { headers: { Accept: "application/vnd.github+json" } }),
      fetch(`https://api.github.com/search/issues?q=repo:a-shygun/${repository}+is:pr+is:open`, { headers: { Accept: "application/vnd.github+json" } })
    ]);
    if (!repoResponse.ok || !issuesResponse.ok || !pullsResponse.ok) throw new Error("GitHub metrics are unavailable");
    const [repo, issues, pulls] = await Promise.all([repoResponse.json(), issuesResponse.json(), pullsResponse.json()]);
    repositoryMetricValues.set(repository, { stars: repo.stargazers_count, issues: issues.total_count, pulls: pulls.total_count });
    renderRepositoryMetrics();
  }));
}

themeToggle.addEventListener("click", () => applyTheme(theme === "dark" ? "light" : "dark"));
languageToggle.addEventListener("click", () => applyLanguage(language === "en" ? "fa" : "en"));
const contributionGraph = document.querySelector("#contribution-graph");
const contributionFallback = document.querySelector("#contribution-fallback");
contributionGraph.addEventListener("error", () => {
  contributionGraph.hidden = true;
  contributionFallback.hidden = false;
});
contributionGraph.addEventListener("load", () => {
  contributionGraph.hidden = false;
  contributionFallback.hidden = true;
});
applyLanguage(language);
applyTheme(theme);
loadRepositoryMetrics();
